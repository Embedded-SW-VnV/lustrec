let pp_print_version fmt () =
  fprintf fmt
    "/* @[<v>C code generated by %s@,\
     Version number %s@,\
     Code is %s compliant@,\
     Using %s numbers */@,\
     @]"
    (Filename.basename Sys.executable_name)
    Version.number
    (if !Options.ansi then "ANSI C90" else "C99")
    (if !Options.mpfr then "MPFR multi-precision"
    else "(double) floating-point")

