let mk_local n m =
  let used name =
    let open List in
    exists (var_is name) m.mstep.step_inputs
    || exists (var_is name) m.mstep.step_outputs
    || exists (var_is name) m.mstep.step_locals
    || exists (var_is name) m.mmemory
  in
  mk_new_name used n

