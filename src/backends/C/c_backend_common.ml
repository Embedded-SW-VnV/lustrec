let mk_loop_var m () =
  let vars =
    m.mstep.step_inputs @ m.mstep.step_outputs @ m.mstep.step_locals @ m.mmemory
  in
  let rec aux () =
    incr loop_cpt;
    let s = sprintf "__%s_%d" "i" !loop_cpt in
    if List.exists (var_is s) vars then aux () else s
  in
  aux ()

